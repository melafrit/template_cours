#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""La série de podcasts (module 03) : des épisodes bruts aux fichiers publiés, puis à la page et aux encadrés.

    python3 outils/generer_podcasts.py           # convertit, rend les diapositives, réécrit la page et les encadrés
    python3 outils/generer_podcasts.py --essai   # ce qui serait fait, sans rien écrire (code 1 s'il reste à faire)

L'auteur dépose dans Podcasts/fr/ et Podcasts/en/ — jamais versionnés (.gitignore), jamais publiés (hors de site/) —
les épisodes exportés de NotebookLM ou d'ElevenLabs, sous les noms de outils/podcasts.py et avec leur extension
d'origine (chapitre-1-podcast.wav, chapitre-1-podcast.m4a…), et leurs diaporamas au même nom (chapitre-1-podcast.pdf).
Pour chaque langue, le script :

  1. convertit chaque épisode brut en MP3 publié (site/assets/media/podcasts/<nom>.<lg>.mp3) : mono, 64 kbit/s,
     44,1 kHz — une voix n'a pas besoin de plus —, étiquettes ID3 (titre, auteur, série) ; seulement si le MP3 manque
     ou si l'épisode brut est plus récent. ffmpeg écrit d'abord un fichier provisoire, que ffprobe contrôle (une durée
     d'au moins DUREE_MIN secondes) avant de le mettre en place ;
  2. copie chaque diaporama pour le téléchargement (<nom>.<lg>.pdf) et rend ses pages en WebP avec PyMuPDF et
     Pillow : une grande image de GRANDE pixels de large et une vignette de VIGNETTE pixels, dans
     site/assets/media/podcasts/diaporamas/<nom>.<lg>/ (diapo-01.webp, vignette-01.webp…) ; seulement si le PDF
     change ou si une image manque ; les images d'une page disparue s'effacent.

Puis il lance outils/generer_fragments.py, qui réécrit la page Podcasts et les encadrés « Le podcast du chapitre »
d'après ce qui est publié. Rien ne s'écrit qui ne change : une seconde passe ne touche à rien. Le MP3 et le diaporama
publiés font foi : l'épisode brut peut quitter Podcasts/ après la conversion. Un fichier mal nommé est signalé, jamais
converti ; deux épisodes bruts pour le même épisode, aucun des deux. Repris, en générique et bilingue, du cours
d'architecture logicielle.
"""
import argparse
import io
import os
import re
import shutil
import subprocess
import sys

RACINE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(RACINE, "outils"))
import podcasts as P  # noqa: E402

for flux in (sys.stdout, sys.stderr):
    try:
        flux.reconfigure(encoding="utf-8")
    except Exception:
        pass

DEBIT, CANAUX, FREQUENCE = "64k", "1", "44100"   # MP3 publié : 64 kbit/s, mono, 44,1 kHz
DUREE_MIN = 30                                    # en secondes : un épisode plus court est une conversion ratée
GRANDE = 1600                                     # largeur d'une diapositive agrandie, en pixels
VIGNETTE = 320                                    # largeur d'une vignette : 168 px affichés, deux fois plus denses
QUALITE_GRANDE, QUALITE_VIGNETTE = 80, 72         # qualité WebP
PAGES_MAX = 80                                    # un diaporama de plus de pages n'est pas le bon fichier
POIDS_ALERTE = 40 << 20                           # au-delà de 40 Mo, un diaporama se signale (il se télécharge)
SOURCES = "Podcasts"                              # le dossier des dépôts, à la racine du dépôt
IGNORES = {".gitignore", "desktop.ini", "thumbs.db", ".ds_store"}
IMAGE = re.compile(r"(diapo|vignette)-(\d+)\.webp")
SERIE = {"fr": "{titre} — les podcasts du cours", "en": "{titre} — The course podcasts"}
COMMENTAIRE = {
    ("fr", "notebooklm"): "Voix générées par IA avec NotebookLM, d'après le cours de {auteur}",
    ("fr", "auteur"): "Voix clonée de l'auteur (ElevenLabs), d'après le cours de {auteur}",
    ("en", "notebooklm"): "Voices generated by AI with NotebookLM, from the course by {auteur}",
    ("en", "auteur"): "The author's cloned voice (ElevenLabs), from the course by {auteur}",
}
NOM_LANGUE = {"fr": "français", "en": "anglais"}


def relatif(p):
    return os.path.relpath(p, RACINE).replace(os.sep, "/")


def publie(rel):
    """Un fichier publié (chemin depuis la racine du site), depuis la racine du dépôt."""
    return "site/" + rel


def titre_cours(lg):
    """Le titre du cours dans la langue, lu dans site/assets/js/course-data.js (title)."""
    try:
        src = io.open(os.path.join(P.SITE, "assets", "js", "course-data.js"), encoding="utf-8").read()
    except OSError:
        return ""
    m = re.search(r"\btitle:\s*\{([^}]*)\}", src)
    t = m and re.search(r"\b%s:\s*\"([^\"]*)\"" % lg, m.group(1))
    return t.group(1) if t else ""


def duree_ffprobe(p):
    """La durée d'un fichier audio en secondes (ffprobe), ou None."""
    try:
        r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of",
                            "default=nw=1:nk=1", p], capture_output=True, text=True, timeout=120)
        return float(r.stdout.strip())
    except (OSError, ValueError, subprocess.SubprocessError):
        return None


def meme_contenu(a, b):
    """Vrai si les deux fichiers existent et ont le même contenu."""
    if not (os.path.isfile(a) and os.path.isfile(b)) or os.path.getsize(a) != os.path.getsize(b):
        return False
    with open(a, "rb") as fa, open(b, "rb") as fb:
        while True:
            x, y = fa.read(1 << 20), fb.read(1 << 20)
            if x != y:
                return False
            if not x:
                return True


def texte_fr(s):
    return s.replace("\u00a0", " ")


# ── 0. les fichiers déposés ─────────────────────────────────────────────────
def sources(lg):
    """Ce que l'auteur a déposé pour une langue : (épisodes bruts {num: chemin}, diaporamas {num: chemin}, fichiers
    inattendus, erreurs)."""
    dossier = os.path.join(RACINE, SOURCES, lg)
    par_nom = {e["nom"]: e["num"] for e in P.EPISODES}
    audio, diapos, inattendus, erreurs, doublons = {}, {}, [], [], {}
    if not os.path.isdir(dossier):
        return audio, diapos, inattendus, erreurs
    for f in sorted(os.listdir(dossier)):
        p = os.path.join(dossier, f)
        if not os.path.isfile(p) or f.lower() in IGNORES or f.startswith("."):
            continue
        base, ext = os.path.splitext(f)
        if base in par_nom and ext.lower() == ".pdf":
            diapos[par_nom[base]] = p
        elif base in par_nom and ext.lower() in P.EXTENSIONS_AUDIO:
            doublons.setdefault(par_nom[base], []).append(p)
        else:
            inattendus.append(relatif(p))
    for num, chemins in sorted(doublons.items()):
        if len(chemins) == 1:
            audio[num] = chemins[0]
        else:                                    # lequel est le bon ? On ne devine pas : rien n'est converti
            erreurs.append("plusieurs épisodes bruts pour l'épisode %d : %s — n'en gardez qu'un"
                           % (num, ", ".join(relatif(c) for c in chemins)))
    return audio, diapos, inattendus, erreurs


# ── 1. l'audio ──────────────────────────────────────────────────────────────
def convertir(src, dst, ep, lg, total):
    """L'épisode brut src en MP3 publié dst ; rend sa durée, ou lève RuntimeError."""
    auteur = texte_fr(P.auteur())
    titre = texte_fr(P.libelle("lecteur", lg, n=ep["num"], titre=P.texte(ep, "titre", lg)))
    provisoire = dst[:-4] + ".provisoire.mp3"
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    commande = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y", "-i", src, "-vn",
                "-map_metadata", "-1", "-ac", CANAUX, "-ar", FREQUENCE, "-c:a", "libmp3lame", "-b:a", DEBIT,
                "-id3v2_version", "3",
                "-metadata", "title=" + titre, "-metadata", "artist=" + auteur, "-metadata", "album_artist=" + auteur,
                "-metadata", "album=" + SERIE[lg].format(titre=titre_cours(lg)),
                "-metadata", "track=%d/%d" % (ep["num"], total), "-metadata", "genre=Podcast",
                "-metadata", "comment=" + COMMENTAIRE[(lg, ep["voix"])].format(auteur=auteur),
                "-f", "mp3", provisoire]
    try:
        r = subprocess.run(commande, capture_output=True, text=True, encoding="utf-8", errors="replace",
                           timeout=3600)
    except (OSError, subprocess.SubprocessError) as ex:
        raise RuntimeError("ffmpeg n'a pas pu être lancé (%s)" % ex)
    if r.returncode:
        if os.path.exists(provisoire):
            os.remove(provisoire)
        raise RuntimeError("ffmpeg : " + (r.stderr.strip().splitlines() or ["échec"])[-1])
    d = duree_ffprobe(provisoire)
    if not d or d < DUREE_MIN:
        os.remove(provisoire)
        raise RuntimeError("le MP3 produit dure %.0f s : moins de %d s, conversion refusée" % (d or 0, DUREE_MIN))
    try:
        os.replace(provisoire, dst)
    except OSError as ex:                        # le MP3 publié est ouvert ailleurs (lecteur, serveur local…)
        os.remove(provisoire)
        raise RuntimeError("%s n'a pas pu être remplacé (%s) — fermez ce qui le lit, puis relancez" % (relatif(dst), ex))
    return d


def audio(lg, bruts, essai, journal, erreurs):
    """Convertit les épisodes bruts plus récents que leur MP3 (ou sans MP3) ; rend les numéros à convertir."""
    a_convertir = set()
    eps = {e["num"]: e for e in P.EPISODES}
    if bruts and not essai and not (shutil.which("ffmpeg") and shutil.which("ffprobe")):
        erreurs.append("ffmpeg et ffprobe sont nécessaires pour convertir les épisodes (introuvables dans le PATH)")
        return a_convertir
    for num, src in sorted(bruts.items()):
        ep = eps[num]
        dst = P.chemin(P.fichiers(ep, lg)["mp3"])
        if os.path.isfile(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
            continue
        if essai:
            a_convertir.add(num)
            d = duree_ffprobe(src) if shutil.which("ffprobe") else None
            journal.append("%s (depuis %s%s)" % (relatif(dst), relatif(src),
                                                 ", " + texte_fr(P.duree_texte(d, "fr")) if d else ""))
            continue
        print("  conversion : %s → %s…" % (relatif(src), relatif(dst)), flush=True)
        try:
            d = convertir(src, dst, ep, lg, len(eps))
        except RuntimeError as ex:
            erreurs.append("épisode %d (%s) : %s" % (num, relatif(src), ex))
            continue
        a_convertir.add(num)
        journal.append("%s — %s, %s" % (relatif(dst), texte_fr(P.duree_texte(d, "fr")),
                                        texte_fr(P.poids_texte(os.path.getsize(dst), "fr"))))
    return a_convertir


# ── 2. les diaporamas ───────────────────────────────────────────────────────
def images_completes(dossier, n):
    return all(os.path.isfile(os.path.join(dossier, P.nom_image(s, i, n)))
               for i in range(1, n + 1) for s in ("diapo", "vignette"))


def webp(image, qualite):
    """L'image en WebP : les mêmes pixels donnent toujours les mêmes octets (rien ne se réécrit sans changer)."""
    tampon = io.BytesIO()
    image.save(tampon, "WEBP", quality=qualite, method=6)
    return tampon.getvalue()


def rendre(pdf, dossier):
    """Rend chaque page du PDF en deux WebP (grande image, vignette) dans dossier ; n'écrit que ce qui change et efface
    les images en trop. Rend (nombre de pages, nombre d'images écrites)."""
    import fitz
    from PIL import Image
    os.makedirs(dossier, exist_ok=True)
    ecrites, attendus = 0, set()
    with fitz.open(pdf) as d:
        n = d.page_count
        for i, page in enumerate(d, 1):
            zoom = GRANDE / page.rect.width
            pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
            image = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
            petite = image.resize((VIGNETTE, max(1, round(VIGNETTE * image.height / image.width))), Image.LANCZOS)
            for sorte, img, qualite in (("diapo", image, QUALITE_GRANDE), ("vignette", petite, QUALITE_VIGNETTE)):
                nom = P.nom_image(sorte, i, n)
                attendus.add(nom)
                octets = webp(img, qualite)
                cible = os.path.join(dossier, nom)
                if not os.path.isfile(cible) or open(cible, "rb").read() != octets:
                    with open(cible, "wb") as f:
                        f.write(octets)
                    ecrites += 1
    for f in os.listdir(dossier):
        if IMAGE.fullmatch(f) and f not in attendus:
            os.remove(os.path.join(dossier, f))
    return n, ecrites


def diaporamas(lg, pdfs, essai, journal, erreurs, alertes):
    """Copie et rend les diaporamas qui changent ; rend les numéros à rendre."""
    a_rendre = set()
    eps = {e["num"]: e for e in P.EPISODES}
    for num, src in sorted(pdfs.items()):
        f = P.fichiers(eps[num], lg)
        pdf, dossier = P.chemin(f["pdf"]), P.chemin(f["diapos"])
        try:
            import fitz
            with fitz.open(src) as d:
                if d.needs_pass:
                    raise RuntimeError("protégé par un mot de passe")
                n = d.page_count
        except Exception as ex:                 # PDF illisible, protégé, ou PyMuPDF absent
            erreurs.append("diaporama de l'épisode %d (%s) : %s" % (num, relatif(src), ex))
            continue
        if not 1 <= n <= PAGES_MAX:
            erreurs.append("diaporama de l'épisode %d (%s) : %d pages, de 1 à %d attendues"
                           % (num, relatif(src), n, PAGES_MAX))
            continue
        if os.path.getsize(src) > POIDS_ALERTE:
            alertes.append("diaporama de l'épisode %d : %s à télécharger — lourd pour un téléphone"
                           % (num, texte_fr(P.poids_texte(os.path.getsize(src), "fr"))))
        if meme_contenu(src, pdf) and images_completes(dossier, n):
            continue
        if essai:
            a_rendre.add(num)
            journal.append("%s et %s/ (%d diapositives, depuis %s)" % (publie(f["pdf"]), publie(f["diapos"]), n,
                                                                       relatif(src)))
            continue
        print("  diaporama : %s → %s/…" % (relatif(src), publie(f["diapos"])), flush=True)
        if not meme_contenu(src, pdf):
            os.makedirs(os.path.dirname(pdf), exist_ok=True)
            shutil.copyfile(src, pdf)
            if not meme_contenu(src, pdf):
                erreurs.append("copie incomplète : " + publie(f["pdf"]))
                continue
        try:
            n, ecrites = rendre(pdf, dossier)
        except Exception as ex:
            erreurs.append("diaporama de l'épisode %d : rendu impossible (%s)" % (num, ex))
            continue
        a_rendre.add(num)
        journal.append("%s et %s/ — %d diapositives, %d image(s) écrite(s)" % (publie(f["pdf"]), publie(f["diapos"]),
                                                                              n, ecrites))
    return a_rendre


# ── 3. la page et les encadrés ──────────────────────────────────────────────
def fragments(essai):
    """Lance outils/generer_fragments.py ; rend (code, sortie)."""
    commande = [sys.executable, os.path.join(RACINE, "outils", "generer_fragments.py")] + (["--essai"] if essai else [])
    r = subprocess.run(commande, capture_output=True, text=True, encoding="utf-8", errors="replace",
                       env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    return r.returncode, (r.stdout + r.stderr).rstrip()


# ── le tableau ──────────────────────────────────────────────────────────────
def tableau(lg, bruts, a_publier, essai):
    """L'état de chaque épisode d'une langue ; a_publier : ceux que cette passe publie (ou publierait, en essai)."""
    print("\n%s — %s/%s/ → site/%s/" % (NOM_LANGUE[lg], SOURCES, lg, P.MEDIA))
    if not P.EPISODES:
        print("  aucun épisode dans outils/podcasts.py")
    for ep in sorted(P.EPISODES, key=lambda e: e["num"]):
        num = ep["num"]
        if P.disponible(ep, lg):
            d = P.duree_mp3(P.chemin(P.fichiers(ep, lg)["mp3"]))
            etat = "en ligne" + (" · " + texte_fr(P.duree_texte(d, "fr")) if d else "")
        else:
            etat = "à venir" + ("" if num in bruts else
                                " — déposez %s/%s/%s.<wav|m4a|mp3…>" % (SOURCES, lg, ep["nom"]))
        diapos = P.diaporama(ep, lg)
        if diapos:
            etat += " · diaporama : %d diapositive%s" % (diapos["n"], "s" if diapos["n"] > 1 else "")
        if num in a_publier:
            etat = ("à publier — " if essai else "publié par cette passe — ") + etat
        print("  %2d  %-34s %s" % (num, ep["nom"], etat))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--essai", action="store_true", help="ce qui serait fait, sans rien écrire")
    args = ap.parse_args()
    problemes = P.controler()
    if problemes:
        for p in problemes:
            print("  ✗", p)
        print("Source incohérente (outils/podcasts.py) — rien n'est fait.")
        return 1
    journal, alertes, erreurs, publies = [], [], P.places_manquantes(), 0
    for lg in P.LANGUES:
        if not args.essai:                       # les restes d'une conversion interrompue
            os.makedirs(os.path.join(RACINE, SOURCES, lg), exist_ok=True)
            dossier = P.chemin(P.MEDIA)
            if os.path.isdir(dossier):
                for f in os.listdir(dossier):
                    if f.endswith(".provisoire.mp3"):
                        os.remove(os.path.join(dossier, f))
        bruts, pdfs, inattendus, err = sources(lg)
        erreurs += err
        a_publier = audio(lg, bruts, args.essai, journal, erreurs) | diaporamas(lg, pdfs, args.essai, journal,
                                                                               erreurs, alertes)
        publies += len(a_publier)
        tableau(lg, bruts, a_publier, args.essai)
        for f in inattendus:
            alertes.append("fichier inattendu, laissé de côté : %s — noms attendus : ceux de outils/podcasts.py "
                           "(<nom>.<wav|m4a|mp3…>, <nom>.pdf)" % f)
    print()
    for a in alertes:
        print("  · " + a)
    for j in journal:
        print(("  à faire : " if args.essai else "  écrit : ") + j)
    for e in erreurs:
        print("  ✗ " + e)
    code, sortie = fragments(args.essai)
    if args.essai and publies:
        print("  puis : la page Podcasts et les encadrés, réécrits d'après ce qui sera publié")
    print("\noutils/generer_fragments.py%s :" % (" --essai" if args.essai else ""))
    print("\n".join("  " + l for l in sortie.splitlines()))
    if not journal and not erreurs and not code:
        print("\nRien à faire : les épisodes, les diaporamas, la page et les encadrés sont à jour.")
    return 1 if erreurs or code or (args.essai and journal) else 0


if __name__ == "__main__":
    sys.exit(main())
